/*  ---------------------------------------------------------------------------
 *  Перевірка часу з мережі (ПОТУЖНЕ РАДІО 1.0.2, ES3C35P).
 *
 *  SNTP ядра (lwIP в Arduino-ESP32 3.3.3) бере будь-яку відповідь сервера: він зібраний із SNTP_CHECK_RESPONSE 0 і
 *  не дивиться ні на LI = 3 («сервер не синхронізований»), ні на страту, ні на адресу відправника. Один сервер пулу
 *  з хибним годинником — і радіо показує хибний час, а будильник спрацьовує не тоді. Так було 14.11.2026:
 *  62.149.0.30 (зона ua пулу) кілька годин відставав на 12–24 год, годинник Informer Clock UA узяв його час.
 *
 *  Час від SNTP ядро ставить функцією sntp_sync_time() — вона «слабка», і її можна замінити своєю (так і задумано
 *  в esp_sntp.h). Наша (yoNtpCheck.cpp):
 *    - годинник знає час, а новий відрізняється не більш ніж на хвилину — ставимо одразу, як і раніше;
 *    - стрибок понад хвилину або годинник часу ще не знає (після ввімкнення живленням) — спершу друга думка:
 *      власний запит NTP незалежному серверу іншої мережі /16 (time.google.com, time.cloudflare.com,
 *      time.apple.com) з перевірками відповіді за RFC 4330. Ставимо лише час, з яким згодні два джерела:
 *      SNTP і другий сервер, два другі сервери між собою, або другий сервер і сам годинник (тоді відкидаємо SNTP);
 *    - другого сервера немає (жоден не відповів): годинник часу не знав — беремо час SNTP без перевірки (як
 *      раніше, краще так, ніж «--:--»); знав — лишаємо свій до наступної звірки, а той самий стрибок удруге
 *      поспіль приймаємо.
 *  Кожна перевірка — рядок «##TIME#» у журналі (консоль, hist). Задумка та сама, що в годиннику 1.1.6 (ntp.cpp),
 *  але SNTP ядра лишається: сервери з налаштувань, запасний і перезапуск, коли часу немає (YoExtras::_timeLoop).
 *  ------------------------------------------------------------------------- */
