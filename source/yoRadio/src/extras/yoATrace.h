/*  ---------------------------------------------------------------------------
 *  Запис огинаючої звуку навколо перемикання джерела (команда «atrace»).
 *
 *  Власник 03.11.2026: «при переключенні на радіо після проповідей — короткі
 *  гучні звукові артефакти перед початком нормального звуку». Щоб знайти, звідки
 *  вони, пишемо з часом: що дає декодер (до обробки), що йде в I2S (після обробки
 *  й затихання), що чує мікрофон кодека (тобто що справді звучить у кімнаті), і
 *  події плеєра — команди, з'єднання, зміну частоти, MUTE.
 *
 *  «atrace 6000» — почати на 6 с, «atrace dump» — надрукувати (по 10 мс).
 *  Поки не ввімкнено — у гарячій точці звуку лише одна перевірка прапорця.
 *  ------------------------------------------------------------------------- */
#pragma once
#include <Arduino.h>

namespace atrace {
  extern volatile bool on;
  void arm(uint32_t ms);
  void sample(int16_t inL, int16_t inR, uint32_t out, uint32_t fs);   /* Audio::playSample */
  void mic(int32_t peak);                                              /* задача мікрофона, на кожне читання */
  void ev(const char* what, int32_t v = 0);                            /* подія з часом */
  void dump();
}
