#ifndef lcdout_h
#define lcdout_h
/*  Вивід готових смуг у дисплей — спільний для обох плат.

    Меню, головний екран, оновлення й заставка малюють картинку смугами в
    пам'яті (Gfx) і віддають їх сюди. Що далі — справа плати:
      ES3C28P (ILI9341, SPI) — переставити байти й послати DMA прямо з буфера;
      ES3C35P (ST77922, QSPI) — повернути смугу на 90° у власний буфер
                                (у панелі немає апаратного повороту) і послати.

    buf — RGB565 у звичайному порядку байтів, рядок за рядком, w×h пікселів,
    координати екранні (ландшафт). lcdPush() починає передачу й повертається:
    true — передача йде просто з buf (його не чіпати до наступного lcdPush або
    lcdEnd); false — buf уже вільний (пікселі скопійовано або виведено).

    ST77922 вимагає, щоб рядки смуги (y і h) були кратні 4 (беремо 8) — див. LCD_ROW_ALIGN.  */
#include <Arduino.h>
#include "../../core/options.h"

#if DSP_MODEL==DSP_ST77922
  /*  Панель вимагає 4 (стиснення блоками по 4 пікселі); беремо 8 — тоді смуга
      повертається цілими блоками 8×8 векторними інструкціями.  */
  #define LCD_ROW_ALIGN 8
  /*  lcdPush() одразу копіює смугу (з поворотом) у свої буфери — смугу можна
      малювати в той самий буфер знову: другий не потрібен, і ціла смуга
      480×32 вміщається там, де були дві по 8 рядків.  */
  #define LCD_PUSH_COPIES 1
#else
  #define LCD_ROW_ALIGN 1
  #define LCD_PUSH_COPIES 0       /* DMA читає просто з буфера — малюємо в другу половину */
#endif

void      lcdBegin();                     /* перед серією смуг */
bool      lcdPush(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t* buf);
void      lcdEnd();                       /* дочекатись кінця всіх передач */
void      lcdWait();                      /* дочекатись, не закриваючи серії (буфер знову вільний) */
/*  Спільний буфер смуг у внутрішній пам'яті (див. spidmaScratch).  */
void*     lcdScratch(size_t bytes);
/*  Перехід між сторінками зсувом — силами самого виводу кадру (як у передатчику
    hearing-link: кадр складається з двох готових листів зі зсувом, сцена заново
    не малюється). lcdSlideBegin(): true — наступні lcdPush пишуть у другий лист,
    його треба намалювати ЦІЛКОМ, і lcdEnd нічого не виводить; потім lcdSlideRun:
    dir 1 — новий в'їжджає справа, -1 — зліва; ms — тривалість. Після нього на
    екрані й у кадрі — другий лист. false — плата так не вміє (ES3C28P).  */
/*  Кадр у пам'яті (ES3C35P): малювати смугу прямо в нього, без lcdPush. Повертає
    адресу точки (x, y) у кадрі (крок рядка — lcdFrameStride()) або nullptr, якщо плата
    так не вміє (ES3C28P). Після малювання — lcdMarked(), щоб частина пішла в панель.  */
uint16_t* lcdFrameFor(int16_t x, int16_t y);
int16_t   lcdFrameStride();
void      lcdMarked(int16_t x, int16_t y, int16_t w, int16_t h);
bool      lcdSlideBegin();
void      lcdSlideRun(int8_t dir, uint32_t ms);
/*  Скільки рядків ширини w уміщує буфер на px пікселів — з урахуванням кратності.  */
static inline int16_t lcdRowsFor(int16_t w, int32_t px){
  int32_t r = w > 0 ? px / w : 0;
  r -= r % LCD_ROW_ALIGN;
  return (int16_t)(r > 0 ? r : 0);
}

#endif
